def _place_directions(lines: dict[tuple[int, int], VoiceLine], spec: PartSpec, m) -> None:
    """Put each dynamic, hairpin, pedal mark and word into the right voice line."""
    keyboard = spec.staves >= 2
    for d in sorted(m.directions, key=lambda d: d.offset):
        mk = _marking(d)
        if mk is None:
            continue
        staff = max(1, min(spec.staves, d.staff or 1))
        if mk.kind == "pedal" and keyboard:
            staff = spec.staves if spec.staves < 3 else 2
        if mk.kind in ("dynamic", "hairpin", "hairpin_end") and keyboard and staff == 2 \
                and d.placement == "above":
            staff = 1
        vl = lines.get((staff, 1)) or next(iter(lines.values()))
        _insert_marking(vl, mk, Fraction(d.offset, DIVISIONS))


def _marking(d: Direction) -> Marking | None:
    if d.kind == "dynamics":
        return Marking("dynamic", d.value)
    if d.kind == "wedge":
        if d.value in ("crescendo", "diminuendo"):
            return Marking("hairpin", d.value)
        return Marking("hairpin_end")
    if d.kind == "pedal":
        if d.value in ("start", "change", "resume"):
            return Marking("pedal", "down")
        if d.value in ("stop", "discontinue"):
            return Marking("pedal", "up")
        return None
    if d.kind == "words" and d.value.strip():
        return Marking("text", d.value.strip(),
                       placement="above" if d.placement == "above" else "")
    return None


def _insert_marking(vl: VoiceLine, mk: Marking, offset: Fraction) -> None:
    mk.offset = offset
    pos = Fraction(0)
    for i, it in enumerate(vl.items):
        if isinstance(it, Event):
            if it.kind == "bar_rest":
                break
            if pos >= offset:
                vl.items.insert(i, mk)
                return
            pos += it.duration
    if vl.items and isinstance(vl.items[0], Event) and vl.items[0].kind == "bar_rest":
        # A whole-bar rest can't carry a mid-bar marking; write the bar out.
        if offset == 0:
            vl.items.insert(0, mk)
            return
    vl.items.append(mk)
